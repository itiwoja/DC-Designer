import { describe, expect, it } from "vitest";
import { addSlidePosition } from "../src/editor/addSlide";

describe("addSlidePosition", () => {
  // 今はスライド 5 を開いていて、全 19 枚
  const pos = (t: string) => addSlidePosition(t, 5, 19);
  it.each([
    ["最後にスライドを1枚追加してほしい、クロージング＋アンケートフォームを投影するQRを添付できるスライド。", 20],
    ["20枚目を追加して", 20],
    ["20枚目にクロージングのスライドを追加して", 20],
    ["30枚目を追加して", 20],
    ["末尾にまとめのスライドを足して", 20],
    ["先頭に目次のスライドを追加", 1],
    ["新しいスライドを作って", 6],
    ["このスライドの前にスライドを1枚挿入して", 5],
    ["もう1枚追加して", 6],
    ["３枚目としてスライドを追加して", 3],
  ])("拾う: %s → %i", (t, n) => expect(pos(t)).toBe(n));
  it.each([
    "スライドに画像を追加して",
    "ページ番号を追加して",
    "タイトルを追加して",
    "3枚目に画像を入れて",
    "台本が無いスライドに台本を追加して",
    "スライド3の内容をこのスライドに追加して",
    "画像をもう1枚追加して",
    "別のスライドの見出しをここに入れて",
  ])("拾わない: %s", (t) => expect(pos(t)).toBeNull());
});
